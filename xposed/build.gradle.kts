        buildConfig = true
    }

    packaging {
        resources.excludes.add("META-INF/*.kotlin_module")
        resources.excludes.add("kotlin/**")
        resources.excludes.add("**/*.kotlin_builtins")
        resources.excludes.add("DebugProbesKt.bin")
